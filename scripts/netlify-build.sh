#!/bin/sh
# Netlify build step: wires the static dashboard to the hosted Vev Audit API.
#   VEV_API_URL   e.g. https://vev-audit-api.onrender.com   (required)
#   VEV_API_MODE  proxy (default) | direct
set -eu

OUT="frontend"
API_URL="${VEV_API_URL:-}"
MODE="${VEV_API_MODE:-proxy}"

if [ -z "$API_URL" ]; then
  echo "ERROR: set VEV_API_URL to your backend URL (e.g. https://vev-audit-api.onrender.com)." >&2
  exit 1
fi
API_URL="${API_URL%/}"
case "$API_URL" in
  https://*) ;;
  *) echo "ERROR: VEV_API_URL must start with https://" >&2; exit 1 ;;
esac

CONNECT_SRC="'self'"
IMG_SRC="'self' data:"
if [ "$MODE" = "direct" ]; then
  CONNECT_SRC="'self' $API_URL"
  IMG_SRC="'self' data: $API_URL"   # annotated screenshots are served by the API
  cat > "$OUT/assets/js/config.js" <<EOF
// Generated by scripts/netlify-build.sh
window.VEV_CONFIG = { apiBase: "$API_URL" };
EOF
  : > "$OUT/_redirects"
  echo "Configured direct API mode -> $API_URL"
else
  cat > "$OUT/_redirects" <<EOF
/api/*  $API_URL/api/:splat  200
EOF
  echo "Configured Netlify proxy: /api/* -> $API_URL/api/*"
fi

cat > "$OUT/_headers" <<EOF
/*
  Content-Security-Policy: default-src 'self'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src $IMG_SRC; connect-src $CONNECT_SRC; frame-ancestors 'none'; base-uri 'self'; form-action 'self'
  X-Content-Type-Options: nosniff
  X-Frame-Options: DENY
  Referrer-Policy: strict-origin-when-cross-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=()
/assets/*
  Cache-Control: public, max-age=3600
EOF
